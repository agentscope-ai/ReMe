@pytest.fixture(name="judge")
def fixture_judge(monkeypatch):
    root = Path(__file__).resolve().parents[2] / "plugins/memlens-judge/src"
    monkeypatch.syspath_prepend(str(root))
    from judge_memlens import protocol
    from judge_memlens.llm_judge import MemLensJudgeStep

    step = MemLensJudgeStep()
    step.context = RuntimeContext.from_context(
        None,
        question="QUESTION",
        reference="REFERENCE",
        prediction="PREDICTION",
        evidence=["first", "second"],
        category="information_extraction",
    )
    step.as_llm = AsyncMock(
        return_value=ChatResponse(
            content=[TextBlock(text='{"answer_score":1}')],
            is_last=True,
            usage=ChatUsage(100, 10, 0.01, cache_input_tokens=30),
        ),
    )
    return step, protocol, root


@pytest.mark.asyncio
async def test_judge_job_uses_only_official_prompt_and_separate_usage(judge):
    step, protocol, root = judge
    response = await step.execute()
    assert response.success and response.metadata["llm_judge_score"] == 1
    assert response.metadata["usage"]["cache_input_tokens"] == 30
    kwargs = {"category": "information_extraction"}
    expected = protocol.judge_prompt("QUESTION", "REFERENCE", "PREDICTION", **kwargs)
    assert step.as_llm.call_args.args[0][0].get_text_content() == expected
    assert len(step.as_llm.call_args.args[0]) == 1 and not step.as_llm.call_args.kwargs
    text = (root / "judge_memlens/plugin.yaml").read_text()
    parse_plugin_manifest(text, plugin_name="memlens-judge")
    manifest = yaml.safe_load(text)["application_defaults"]
    assert manifest["jobs"]["answer_judge"]["steps"] == [{"backend": "memlens_judge_step", "as_llm": "judge"}]
    model = manifest["components"]["as_llm"]["judge"]
    assert model["extra_body"] == {"enable_thinking": False} and model["parameters"]["temperature"] == 0
    assert model["parameters"]["max_tokens"] == 256
    step.as_llm.return_value = ChatResponse(content=[TextBlock(text="malformed")], is_last=True)
    assert (await step.execute()).metadata["parse_default_zero"] is True
    step.context.data["prediction"] = "word " * 501
    assert (await step.execute()).metadata["auto_zero"] is True
    assert step.as_llm.await_count == 2
    step.context.data["prediction"] = "PREDICTION"
    step.as_llm.side_effect = TimeoutError("provider")
    with pytest.raises(TimeoutError):
        await step.execute()


def test_memlens_official_registry_digests_and_routing(monkeypatch):
    monkeypatch.syspath_prepend(str(Path(__file__).resolve().parents[2] / "plugins/memlens-judge/src"))
    from judge_memlens import protocol

    # Independent upstream build_judge_prompt digests, not generated by this renderer.
    digests = {
        "IE_Entity": "83991403e50c7390f9bafd957618a9ad01bdde2ae6d26ada38ce9954c697ebb0",
        "IE_PreviousInfo": "18082c484f096bef129b6007671f7cde3e9c44b9e1e5e781630b84a604c126f7",
        "KU_KnowledgeUpdate": "ccd52d849c6eb132e819f1f2847faf8a3c1755e517fd7f3e17308d8b51798951",
        "TR_DurationComparison": "b884e6688d2b195c63d25c40c9003d98a5c8915b8b008613b51b14f95cc1c733",
        "TR_OrderRanking": "c57f6b289c986aef4a1c6032c0d5544a7980001354298aaa9b3546c0edb4f86b",
        "TR_DateExtraction": "8c10197630ba720759a6e04a1d670e5af9781284c509d53f89310529ad8d17a5",
        "MSR_YesNo": "79779f253bfee20cfa9666ff33c6cdcc37828b9d17f8c83f92af4ec7e2e557ff",
        "MSR_Counting": "bde797036e6069ac10a649ae80fc6749facd4c1ef5e912f39418fcfe729752a7",
        "MSR_Arithmetic": "089db6580a3a640a5cb925b490e9cd059a71b65d4d85b236b748ee17cb1766af",
        "AR_AnswerRefusal": "c7a6702489c079cfa4c354febb916078825325a0396261627b2c0295aab0d018",
    }
    prompts = protocol._prompts()
    assert prompts["source_revision"] == protocol.SOURCE_REVISION
    assert set(prompts["criteria"]) == set(digests)
    for key, digest in digests.items():
        base = prompts["template"].format(task_criteria=prompts["criteria"][key], examples=prompts["examples"][key])
        reference = "Insufficient information" if key == "AR_AnswerRefusal" else "REFERENCE"
        old = "<Old (Outdated) Answer>: OLD\n" if key == "KU_KnowledgeUpdate" else ""
        rendered = (
            f"{base}[Current Case]\n<Question>: QUESTION\n<Standard Answer>: {reference}\n"
            f"{old}<Student Answer>: PREDICTION\n\n[Scoring Rationale]:"
        )
        assert hashlib.sha256(rendered.encode()).hexdigest() == digest
    assert protocol.task_key("multi_session_reasoning", "entity_resolution", "2") == "MSR_Counting"
    assert protocol.parse_judge_response('{"answer_score":0} [Score]:1')["acc"] == 0
